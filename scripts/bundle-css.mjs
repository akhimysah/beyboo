#!/usr/bin/env node
// Concatenate the stylesheets listed in scripts/stylesheets.json, in order, into
// public/beyboo.bundle.css and stamp its content hash into the single <link> of
// public/index.html (npm run bundle:css). tests/css-bundle.test.mjs verifies that
// neither the bundle nor the stamped hash drifts from the sources.
import {createHash} from 'node:crypto';
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const PUBLIC_DIR = join(ROOT, 'public');
export const INDEX_PATH = join(PUBLIC_DIR, 'index.html');
export const LIST_PATH = join(ROOT, 'scripts', 'stylesheets.json');
export const BUNDLE_PATH = join(PUBLIC_DIR, 'beyboo.bundle.css');
export const BUNDLE_NAME = 'beyboo.bundle.css';

export function stylesheetLinks() {
  return JSON.parse(readFileSync(LIST_PATH, 'utf8')).map(href => {
    const [file, query = ''] = href.split('?');
    return {href, file, query};
  });
}

export function buildBundle() {
  const links = stylesheetLinks();
  const parts = links.map(({file, query}) => {
    const css = readFileSync(join(PUBLIC_DIR, file), 'utf8');
    return `/* ===== ${file}${query ? ` (${query})` : ''} ===== */\n${css.trimEnd()}\n`;
  });
  const css = `/* BEYBOO stylesheet bundle: generated by scripts/bundle-css.mjs from scripts/stylesheets.json. Do not edit; run \`npm run bundle:css\`. */\n${parts.join('\n')}`;
  const hash = createHash('sha256').update(css).digest('hex').slice(0, 10);
  return {css, links, hash, link: `<link rel="stylesheet" href="${BUNDLE_NAME}?v=${hash}">`};
}

export const LINK_PATTERN = /<link rel="stylesheet" href="beyboo\.bundle\.css\?v=[^"]*">/;

function main() {
  const {css, links, hash, link} = buildBundle();
  writeFileSync(BUNDLE_PATH, css);
  const html = readFileSync(INDEX_PATH, 'utf8');
  if (!LINK_PATTERN.test(html)) throw new Error('public/index.html has no beyboo.bundle.css <link>');
  writeFileSync(INDEX_PATH, html.replace(LINK_PATTERN, link));
  console.log(`${BUNDLE_NAME}: ${Buffer.byteLength(css).toLocaleString('en-US')} bytes from ${links.length} stylesheets, hash ${hash} stamped into public/index.html`);
  console.log('Remember: python3 -I scripts/render-english-page.py regenerates public/index-en.html.');
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) main();
